        function requestNotificationPermission() {
          if (permissionRequested) return
          permissionRequested = true
          try {
            if (typeof document === 'undefined' || typeof document.addEventListener !== 'function') return
            const ask = () => {
              try {
                const result = Notification.requestPermission()
                if (result !== undefined && typeof result.then === 'function') {
                  result.then((permission) => {
                    if (permission === 'granted') void refreshWatch()
                  }).catch(() => {})
                }
              } catch {
                // permission prompts are best-effort only
              }
            }
            document.addEventListener('pointerdown', ask, { once: true })
            document.addEventListener('keydown', ask, { once: true })
          } catch {
            // no permission prompt available
          }
        }

        function notifyAlert(alert) {
          try {
            if (alert === undefined || alert === null || !(alert.level >= 1)) return
            const options = readOptions()
            if (hostSettings.notify === false) return
            if (options.monitor !== true) return
            const focused = typeof document !== 'undefined' && typeof document.hasFocus === 'function' ? document.hasFocus() : false
            const hidden = typeof document !== 'undefined' && document.hidden === true
            if (options.onlyWhenUnfocused !== false && focused && hidden === false) return
            if (typeof Notification === 'undefined') return
            if (Notification.permission !== 'granted') {
              if (Notification.permission === 'default') requestNotificationPermission()
              return
            }
            const volume = alert.volume !== undefined ? alert.volume : watchSnapshot.volumes[0]
            const title = alert.level >= 2 ? t('notify.critical.title') : t('notify.warn.title')
            const body = t(alert.level >= 2 ? 'notify.critical.body' : 'notify.warn.body', {
              volume: volume === undefined ? '' : volumeTitle(volume, t),
              free: volume === undefined ? '—' : formatBytes(volume.free),
              pct: volume === undefined || volume.total <= 0 ? '—' : formatPercent(volume.free / volume.total),
            })
            const notification = new Notification(title, { body })
            if (notification !== null && typeof notification === 'object' && 'onclick' in notification) {
              notification.onclick = () => {
                try {
                  if (typeof window !== 'undefined' && typeof window.focus === 'function') window.focus()
                  ctx.layout.selectPanel(PANEL_ID)
                } catch {
                  // focusing is best-effort
                }
              }
            }
          } catch {
            // notifications must never break the panel
          }
        }

        const refreshWatch = async () => {
          try {
            const response = await fetch(`${API}/watch`, { headers: { accept: 'application/json' } })
            const data = await response.json()
            if (data.ok !== true) return
            const seq = typeof data.seq === 'number' ? data.seq : 0
            if (lastSeenSeq === undefined) {
              // Adopt the current state without firing a notification on load.
              lastSeenSeq = seq
            } else if (seq > lastSeenSeq) {
              lastSeenSeq = seq
              notifyAlert(data.lastAlert)
            }
            const level = typeof data.level === 'number' ? data.level : 0
            const volumes = Array.isArray(data.volumes) ? data.volumes : watchSnapshot.volumes
            if (
              watchSnapshot.ready !== true ||
              watchSnapshot.level !== level ||
              watchSnapshot.seq !== seq ||
              watchSnapshot.volumes !== volumes
            ) {
              watchSnapshot = { ready: true, level, seq, volumes }
              for (const listener of watchListeners) {
                try {
                  listener()
                } catch {
                  // a listener must never break the watcher
                }
              }
            }
          } catch {
            // Disk telemetry is best-effort; the panel shows the real state.
          }
        }

