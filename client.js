        function buildReport(workspace, volume, data) {
          const lines = []
          lines.push(t('report.workspace', { title: workspace.title }))
          lines.push('')
          lines.push(t('report.path', { path: workspace.path }))
          if (volume !== undefined) {
            lines.push(
              t('report.volume', {
                free: formatBytes(volume.free),
                total: formatBytes(volume.total),
                used: formatPercent(volume.total > 0 ? volume.used / volume.total : 0),
              }),
            )
          }
          lines.push(t('report.total', { size: formatBytes(data.total) }))
          if (typeof data.scannedAt === 'number') lines.push(t('report.measuredAt', { time: formatTime(data.scannedAt) }))
          lines.push('')
          lines.push(t('report.tableHead'))
          lines.push(t('report.tableRule'))
          for (const entry of Array.isArray(data.entries) ? data.entries : []) {
            lines.push(`| ${entry.name}/ | ${formatBytes(entry.size)} |`)
          }
          const rest = data.rest === undefined ? { count: 0, size: 0 } : data.rest
          if (rest.count > 0) lines.push(t('report.rest', { count: rest.count, size: formatBytes(rest.size) }))
          return lines.join('\n')
        }

