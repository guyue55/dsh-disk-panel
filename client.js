    const GIB = 1024 ** 3

    /** Mirrors the Host watchdog: ratio thresholds (lower for huge volumes) or absolute free space. */
    function severityFor(volume) {
      const free = Number(volume.free)
      const total = Number(volume.total)
      if (!Number.isFinite(free) || !Number.isFinite(total) || total <= 0) return 0
      const ratio = free / total
      const big = total >= 1024 ** 4
      const warnRatio = big ? 0.05 : 0.1
      const critRatio = big ? 0.02 : 0.05
      if (ratio <= critRatio || free <= 5 * GIB) return 2
      if (ratio <= warnRatio || free <= 20 * GIB) return 1
      return 0
    }

